"""Step 7  -  the two advanced LaTeX tables plus a compile proof.

Table 1  Reporting-Delay Atlas   : in-cell data bars + right-edge delay-CDF sparklines
Table 2  Nowcast Scoreboard      : continuous \\cellcolor heatmap shading, paired
                                   naive/nowcast rows, improvement markers

Every printed number is read from a results file; nothing is hand-typed.
Compiles a standalone preview under trbunofficial.cls to prove the tables render;
falls back to data-bars-only (no TikZ) if the sparklines fight the class.

Outputs
  results/tables/tables_preamble.tex, table1.tex, table2.tex,
                 tables_preview.tex, tables_preview.pdf
  results/audits/tables_audit.json
"""

