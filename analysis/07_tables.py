SEV_NAME = {0: "No injury (Y0)", 1: "Crash/fire (Y1)", 2: "Injury (Y2)",
            3: "Fatality (Y3)"}
# VOQ is the vehicle owner's questionnaire itself; the web channel is IVOQ.
# Labels follow NHTSA's published CMPL_TYPE field definitions.
CHAN_NAME = {"IVOQ": "Internet (IVOQ)", "EVOQ": "Hotline (EVOQ)",
             "VOQ": "Questionnaire (VOQ)", "MAVQ": "Mobile app (MAVQ)"}


def esc(s):
    return str(s).replace("%", "\\%").replace("&", "\\&").replace("_", "\\_")


DAY_MAX = 1200.0          # log axis upper bound, just above the largest P90 (1,182 d)
GLYPH_W = "13mm"          # width of the delay-spread glyph column
GLYPH_TICKS = (1, 10, 100, 1000)


def _logx(v):
    """Days -> [0,1] on a log(1+x) axis shared by every row of Table 1."""
    return float(np.clip(np.log10(1.0 + max(float(v), 0.0))
                         / np.log10(1.0 + DAY_MAX), 0.0, 1.0))


def distglyph(p25, p50, p75, p90):
    """Compact box-and-whisker of the delay distribution on a shared log axis.

    Replaces the earlier CDF sparkline, which shared no axis with the numeric
    columns and could not be read row to row. The box spans the quartiles, the
    heavy tick is the median, and the whisker runs to P90, so the glyph is a
    picture of the four numbers printed immediately to its left. Symmetric about
    y = 0 and given a small negative baseline so it centres on the row text.
    """
    a, m, b, w = _logx(p25), _logx(p50), _logx(p75), _logx(p90)
    grid = "".join(f"\\draw[glyphgrid] ({_logx(t):.3f},-1.25) -- ({_logx(t):.3f},1.25);"
                   for t in GLYPH_TICKS)
    return (f"\\begin{{tikzpicture}}[x={GLYPH_W},y=1mm,baseline=-0.75mm]"
            + grid
            + "\\draw[glyphaxis] (0,0) -- (1,0);"
            f"\\draw[whisker] ({b:.3f},0) -- ({w:.3f},0);"
            f"\\draw[whisker] ({w:.3f},-0.62) -- ({w:.3f},0.62);"
            f"\\fill[barfill] ({a:.3f},-0.95) rectangle ({b:.3f},0.95);"
            f"\\draw[medtick] ({m:.3f},-1.25) -- ({m:.3f},1.25);"
            "\\end{tikzpicture}")


def glyph_axis():
    """Header strip for the glyph column: tick labels at their true log positions."""
    labs = {1: "1", 10: "10", 100: "100", 1000: "1k"}
    nodes = "".join(
        f"\\node[anchor=base,inner sep=0pt,font=\\tiny] at ({_logx(t):.3f},0) "
        f"{{{labs[t]}}};" for t in GLYPH_TICKS)
    return (f"\\begin{{tikzpicture}}[x={GLYPH_W},y=1mm,baseline=0mm]"
            + nodes + "\\end{tikzpicture}")


def bar(frac, label):
    return f"\\dbar{{{max(0.0, min(1.0, frac)):.3f}}}{{{label}}}"


def shade(x, vmax):
    """|value| -> (hex background, needs-white-text) on the light-gray->navy ramp."""
    t = float(np.clip(abs(x) / vmax, 0, 1))
    r, g, b, _ = fs.HEATMAP_CMAP(0.08 + 0.92 * t)
    lum = 0.2126 * r + 0.7152 * g + 0.0722 * b
    return "%02X%02X%02X" % (round(r * 255), round(g * 255), round(b * 255)), lum < 0.55


